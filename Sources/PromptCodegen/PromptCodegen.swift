import Foundation

/// Turns the Markdown prompt files in `Sources/TalkToMyMacCore/Prompts` into Swift source, so
/// the prompts are compiled into the app instead of loaded at runtime. Used by the
/// `PromptCompiler` tool, which the `PromptCompilerPlugin` build plugin runs on every build.
public enum PromptCodegen {
    public enum Error: Swift.Error, Equatable, CustomStringConvertible {
        case duplicateIdentifier(String, files: [String])

        public var description: String {
            switch self {
            case let .duplicateIdentifier(identifier, files):
                return "Prompt files \(files.joined(separator: ", ")) all map to `\(identifier)`; rename one."
            }
        }
    }

    /// The Swift name for a prompt file: `clean-up.md` → `cleanUp`.
    public static func identifier(forFileName fileName: String) -> String {
        let words = stem(of: fileName)
            .split { !($0.isLetter || $0.isNumber) }
            .map(String.init)
        guard let first = words.first else { return "_" }
        let name = lowercasingFirst(first) + words.dropFirst().map(capitalizingFirst).joined()
        return name.first?.isNumber == true ? "_" + name : name
    }

    /// The file name without its extension: `clean-up.md` → `clean-up`.
    public static func stem(of fileName: String) -> String {
        guard let dot = fileName.lastIndex(of: "."), dot != fileName.startIndex else { return fileName }
        return String(fileName[..<dot])
    }

    /// The prompt a file holds: its contents with Unix line endings, minus the one trailing
    /// newline editors add.
    public static func promptText(fromFile contents: String) -> String {
        let text = contents.replacingOccurrences(of: "\r\n", with: "\n")
        return text.hasSuffix("\n") ? String(text.dropLast()) : text
    }

    /// A multi-line raw string literal holding `text` verbatim. It uses one more `#` than the
    /// longest run of `#` in the text, so nothing in the text can end the literal or start an
    /// escape.
    public static func rawStringLiteral(_ text: String) -> String {
        let hashes = String(repeating: "#", count: longestRun(of: "#", in: text) + 1)
        return "\(hashes)\"\"\"\n\(text)\n\"\"\"\(hashes)"
    }

    /// The generated `PromptLibrary` source, with prompts sorted by identifier. Throws if two
    /// files map to the same identifier.
    public static func checkedSource(prompts: [(fileName: String, text: String)]) throws -> String {
        let grouped = Dictionary(grouping: prompts, by: { identifier(forFileName: $0.fileName) })
        if let clash = grouped.sorted(by: { $0.key < $1.key }).first(where: { $0.value.count > 1 }) {
            throw Error.duplicateIdentifier(clash.key, files: clash.value.map(\.fileName).sorted())
        }
        return source(prompts: prompts)
    }

    /// The generated `PromptLibrary` source, with prompts sorted by identifier.
    public static func source(prompts: [(fileName: String, text: String)]) -> String {
        let sorted = prompts
            .map { (key: stem(of: $0.fileName), name: identifier(forFileName: $0.fileName), text: $0.text) }
            .sorted { $0.name < $1.name }
        var out = """
        // Generated by PromptCompiler from Sources/TalkToMyMacCore/Prompts/*.md. Do not edit;
        // edit the Markdown files instead.

        /// The built-in prompts, compiled from `Sources/TalkToMyMacCore/Prompts`.
        public enum PromptLibrary {

        """
        for prompt in sorted {
            out += "    /// `Prompts/\(prompt.key).md`\n"
            out += "    public static let \(prompt.name) = \(rawStringLiteral(prompt.text))\n\n"
        }
        out += "    /// Every prompt, keyed by its file name without `.md`.\n"
        out += "    public static let all: [String: String] = [\n"
        for prompt in sorted {
            out += "        \"\(prompt.key)\": \(prompt.name),\n"
        }
        out += "    ]\n}\n"
        return out
    }

    private static func longestRun(of character: Character, in text: String) -> Int {
        var longest = 0, current = 0
        for c in text {
            current = c == character ? current + 1 : 0
            longest = max(longest, current)
        }
        return longest
    }

    private static func lowercasingFirst(_ word: String) -> String {
        word.prefix(1).lowercased() + word.dropFirst()
    }

    private static func capitalizingFirst(_ word: String) -> String {
        word.prefix(1).uppercased() + word.dropFirst()
    }
}
